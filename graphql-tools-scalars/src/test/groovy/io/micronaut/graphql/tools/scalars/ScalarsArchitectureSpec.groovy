package io.micronaut.graphql.tools.scalars

import com.tngtech.archunit.base.DescribedPredicate
import com.tngtech.archunit.core.domain.JavaClass
import com.tngtech.archunit.core.domain.JavaClasses
import com.tngtech.archunit.core.domain.JavaMethod
import com.tngtech.archunit.core.domain.JavaModifier
import com.tngtech.archunit.core.importer.ClassFileImporter
import com.tngtech.archunit.core.importer.ImportOption
import com.tngtech.archunit.lang.ArchCondition
import com.tngtech.archunit.lang.ConditionEvents
import com.tngtech.archunit.lang.SimpleConditionEvent
import spock.lang.Shared
import spock.lang.Specification

import static com.tngtech.archunit.core.domain.JavaClass.Predicates.resideInAPackage
import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.classes
import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses

/**
 * The bytecode of this module obeys the rules that the library has: no Jackson, no reflection on user classes, and no dependency of the
 * public package on the internal ones (the public API names no type that can change in any release), and one accessor style
 * (getX and isX) in every public class, interface and enum.
 */
class ScalarsArchitectureSpec extends Specification {

    static final String ROOT = 'io.micronaut.graphql.tools.scalars'

    @Shared JavaClasses classes = new ClassFileImporter()
            .withImportOption(ImportOption.Predefined.DO_NOT_INCLUDE_TESTS)
            .importPackages(ROOT)

    void "the classes of the module are found"() {
        expect:
        classes.contain('io.micronaut.graphql.tools.scalars.StandardScalar')
        classes.contain('io.micronaut.graphql.tools.scalars.internal.StandardScalarsFactory')
        classes.size() > 10
    }

    void "no class depends on Jackson"() {
        expect:
        noClasses().should().dependOnClassesThat(resideInAPackage('com.fasterxml.jackson..'))
                .because('the module uses the JSON API of Micronaut and Micronaut Serialization, never Jackson')
                .check(classes)
    }

    void "the public package depends on no internal package"() {
        expect:
        noClasses().that().resideInAPackage(ROOT).should().dependOnClassesThat(resideInAPackage(ROOT + '.internal..'))
                .because('a public type that reaches into an internal package ties the API to code that changes in any release')
                .check(classes)
    }

    void "no public class, interface or enum declares a record-style accessor"() {
        expect:
        classes().that().resideInAPackage(ROOT).and().arePublic().and().areNotRecords().and().areNotAnnotations()
                .and(DescribedPredicate.describe('not generated by Micronaut', { JavaClass c -> !c.name.substring(c.packageName.length() + 1).startsWith('$') }))
                .should(declareNoRecordStyleAccessor())
                .because('a public interface, class or enum names its accessors getX and isX; only a record, which is the immutable data carrier, uses the component name (BC-44, BC-52, BC-53)')
                .check(classes)
    }

    private static ArchCondition<JavaClass> declareNoRecordStyleAccessor() {
        new ArchCondition<JavaClass>('declare no public method without parameters that returns a value under a name that is not getX, isX, toX or asX') {
            @Override
            void check(JavaClass item, ConditionEvents events) {
                item.methods.findAll { JavaMethod m ->
                    m.modifiers.contains(JavaModifier.PUBLIC) && !m.modifiers.contains(JavaModifier.STATIC) &&
                            !m.modifiers.contains(JavaModifier.SYNTHETIC) && !m.modifiers.contains(JavaModifier.BRIDGE) &&
                            m.parameters.empty && m.rawReturnType.name != 'void' && !(m.name in ['hashCode', 'toString']) &&
                            !(m.name =~ /^(get|is|to|as)[A-Z]/)
                }.each { JavaMethod m ->
                    events.add(SimpleConditionEvent.violated(m, "${m.fullName} is a record-style accessor in a class, interface or enum"))
                }
            }
        }
    }

    void "no class looks up a class, member or annotation by reflection"() {
        given:
        def reflective = ['forName', 'newInstance', 'getMethod', 'getMethods', 'getDeclaredMethod', 'getDeclaredMethods', 'getField',
                          'getFields', 'getDeclaredField', 'getDeclaredFields', 'getConstructor', 'getConstructors',
                          'getDeclaredConstructor', 'getDeclaredConstructors', 'getAnnotation', 'getAnnotations', 'isAnnotationPresent',
                          'getEnumConstants'] as Set
        def offenders = classes.collectMany { JavaClass c ->
            c.methodCallsFromSelf.findAll { it.target.owner.name == 'java.lang.Class' && it.target.name in reflective }
                    .collect { "${c.name} calls Class.${it.target.name}".toString() }
        }

        expect:
        assert offenders.empty: offenders.join('\n')
    }

}
